"""Versioned bundled activities. Mystery metadata never names the diagnosis.

Definitions are independent of installed packs. Reward keys are stable identities,
not display names or version numbers. Private rubrics live in fixtures.py.
"""

SKILLS = {
    "access": "Apply identity, ownership and action rules to a request",
    "subnet": "Read an IPv4 prefix and compare address ranges",
    "logging": "Filter events and compare request outcomes",
    "integrity": "Compare exact bytes and trusted content digests",
    "timeline": "Order timestamped events and distinguish correlation from proof",
    "python": "Trace a short Python loop, list and filtering condition",
    "spatial": "Apply coordinate translation, scaling and ordered transforms",
}


def activity(
    id,
    title,
    family,
    minutes,
    *,
    kind="quick",
    role="challenge",
    difficulty="easy",
    skills=(),
    format="exercise",
    hints=(),
    brief="",
    strategy="generated",
    reward_key=None,
    domain="cyber",
    version=1,
):
    return dict(
        id=id,
        title=title,
        version=version,
        kind=kind,
        role=role,
        family=family,
        domain=domain,
        minutes=minutes,
        setup_minutes=0,
        difficulty=difficulty,
        skills=list(skills),
        prerequisites=[SKILLS[s] for s in skills],
        preparation=[f"example-{s}" for s in skills],
        preparation_minutes=5 * len(skills),
        topic="investigation" if format == "mystery" else family,
        format=format,
        environment="browser",
        device="phone",
        setup="No setup; all evidence is included",
        verification="Learning notes"
        if role == "example"
        else "Exploration"
        if kind == "free"
        else "Fixture evidence check",
        hint_policy="limited" if hints else "none",
        hints=list(hints),
        review=role == "challenge" and kind != "free",
        brief=brief,
        variant_strategy=strategy,
        reward_key=reward_key or f"ascend:{id}",
        source_node=None,
        award={"easy": 25, "intermediate": 50, "hard": 100}[difficulty]
        if kind == "challenge"
        else 0,
    )


