def get(activity_id):
    for item in CATALOG:
        if item["id"] == activity_id:
            return item
    raise ValueError("Activity not found")


def public(item):
    # Allowlist: private generator names, reward identities and hint contents do
    # not belong in discovery metadata. Preparation is expressed as abilities.
    keys = (
        "id",
        "title",
        "version",
        "kind",
        "role",
        "minutes",
        "setup_minutes",
        "difficulty",
        "prerequisites",
        "preparation",
        "preparation_minutes",
        "topic",
        "format",
        "environment",
        "device",
        "setup",
        "verification",
        "hint_policy",
        "review",
        "brief",
        "variant_strategy",
    )
    return {key: item[key] for key in keys} | {"domain": item.get("domain", "cyber")}
